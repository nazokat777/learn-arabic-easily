DIAC = re.compile(r'[\u064B-\u0652\u0670\u0640]')
def norm(s):
    s = DIAC.sub('', s)
    s = s.replace('أ','ا').replace('إ','ا').replace('آ','ا').replace('ى','ي').replace('ة','ه').replace('ؤ','و').replace('ئ','ي')
    s = re.sub(r'[^\u0621-\u064A]', '', s)
    return s

d = json.loads(Path('app/assets/content/nahv_lessons.json').read_text(encoding='utf-8'))
b4 = [x for x in d['lessons'] if x['book'] == 4]

titles = [(norm(x.get('titleAr') or ''), x['page'], x['num']) for x in b4]
# har darsning butun matni (sarlavha kirmagan sarlavhalar matn ichida bo'lishi mumkin)
bodies = []
for x in b4:
    parts = [(x.get('rule') or {}).get('ar','')]
    for b in x.get('blocks', []):
        parts.append(b.get('ar',''))
        parts.append((b.get('intro') or {}).get('ar','') if isinstance(b.get('intro'), dict) else '')
    bodies.append((norm(' '.join(parts)), x['page'], x['num']))

miss = []
for pg, head in IDX:
    h = norm(head)
    hit = None
    for t, p, n in titles:
        if t and (h in t or t in h) and abs(p - pg) <= 3:
            hit = ('titleAr', n, p); break
    if not hit:
        for t, p, n in titles:            # sahifa cheklovisiz
            if t and (h in t or t in h):
                hit = ('titleAr~', n, p); break
    if not hit:
        for t, p, n in bodies:
            if h and h in t and abs(p - pg) <= 8:
                hit = ('matn', n, p); break
    if not hit:
        miss.append((pg, head))

print('fehrestdagi sarlavhalar:', len(IDX))
print('topilmagan:', len(miss))
for pg, head in miss:
    print('  s.%d  %s' % (pg, head))
