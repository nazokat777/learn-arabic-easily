# ---- Cyrillic (Uzbek) -> Latin (Uzbek) transliteration ----
MULTI = {
    'ё':'yo','ю':'yu','я':'ya','ч':'ch','ш':'sh','щ':'sh',
    'ў':"o'",'ғ':"g'",'қ':'q','ҳ':'h','х':'x','ж':'j','ц':'ts','ъ':"'",'ь':'',
}
SINGLE = {
    'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','з':'z','и':'i','й':'y',
    'к':'k','л':'l','м':'m','н':'n','о':'o','п':'p','р':'r','с':'s','т':'t',
    'у':'u','ф':'f','э':'e','ы':'i',
}

def translit(s):
    out = []
    i = 0
    prev_is_letter = False
    while i < len(s):
        ch = s[i]
        low = ch.lower()
        is_upper = ch != low
        rep = None
        if low in MULTI:
            rep = MULTI[low]
        elif low in SINGLE:
            rep = SINGLE[low]
            # word-initial 'е' -> 'ye'
            if low == 'е' and not prev_is_letter:
                rep = 'ye'
        if rep is None:
            out.append(ch)
            prev_is_letter = ch.isalpha()
            i += 1
            continue
        if is_upper and rep:
            rep = rep[0].upper() + rep[1:]
        out.append(rep)
        prev_is_letter = True
        i += 1
    return ''.join(out)

def v(ar, pl, uz_cyr):
    return {"ar": ar, "pl": pl, "uz": translit(uz_cyr)}

